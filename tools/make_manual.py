def n(x, d=1):
    if x is None:
        return "–"
    if isinstance(x, str):
        return x
    if abs(x) >= 1000:
        return f"{x:,.{d}f}" if d else f"{x:,.0f}"
    return f"{x:.{d}f}"


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    for row in rows:
        out.append("| " + " | ".join(str(c) for c in row) + " |")
    return "\n".join(out)


