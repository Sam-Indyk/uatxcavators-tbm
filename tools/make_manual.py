def checks_md(parts=None, ids=None, cases=None):
    sel = [r_ for r_ in ROWS if (parts is None or r_["part"] in parts) and (ids is None or r_["id"] in ids) and (cases is None or r_["case"] in cases)]
    if not sel:
        return "_No checks._\n"
    rows = []
    for r_ in sel:
        fy = n(r_["fos_yield"], 2) if r_["fos_yield"] else "–"
        status = "ok" if r_["ok"] else "**below**"
        val = n(r_["value"], 2 if abs(r_["value"]) < 10 else 1)
        rows.append([r_["id"], r_["part"], r_["item"], r_["case"], f"{val} {r_['unit']}", f"{n(r_['allow'], 1)} ({r_['basis']})",
                     n(r_["fos"], 2), fy, n(r_["req"], 2) if r_["req"] is not None else "reported", status])
    t = table(["ID", "Part", "Check", "Case", "Value", "Allowable (basis)", "FoS", "FoS yield", "Required", "Status"], rows)
    eqs = []
    for r_ in sel:
        if r_["eq"]:
            line = f"- **{r_['id']} {r_['case']}**: {r_['eq']} → **{n(r_['value'], 2)} {r_['unit']}**"
            if r_["note"]:
                line += f". {r_['note']}"
            eqs.append(line)
    return t + "\n\nEquations behind the rows:\n\n" + "\n".join(eqs) + "\n"


